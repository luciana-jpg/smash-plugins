// Scans public/gen for cXX.mp4 clips and writes src/clips.ts so the
// composition uses a video where one exists and the still otherwise.
import fs from "node:fs";
const files = fs.readdirSync("public/gen").filter((f) => /^c\d\d\.mp4$/.test(f)).sort();
fs.writeFileSync("src/clips.ts", `// generated by scripts/clips-manifest.mjs\nexport const CLIPS: string[] = ${JSON.stringify(files)};\n`);
console.log("clips:", files.length ? files.join(", ") : "(none)");
